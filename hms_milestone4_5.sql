SELECT 'Patients missing first_name'  AS check_name, COUNT(*) AS violations FROM patient     WHERE first_name IS NULL OR first_name = '' UNION ALL
SELECT 'Patients missing phone',                      COUNT(*) FROM patient     WHERE phone IS NULL UNION ALL
SELECT 'Doctors missing license',                     COUNT(*) FROM doctor      WHERE license_number IS NULL UNION ALL
SELECT 'Appointments missing status',                 COUNT(*) FROM appointment WHERE status IS NULL UNION ALL
SELECT 'Medical records missing diagnosis',           COUNT(*) FROM medical_record WHERE diagnosis IS NULL OR diagnosis = '' UNION ALL
SELECT 'Prescriptions missing record_id',             COUNT(*) FROM prescription  WHERE record_id IS NULL UNION ALL
SELECT 'Billing with negative total',                 COUNT(*) FROM billing       WHERE total_amount <= 0 UNION ALL
SELECT 'Rooms with zero price',                       COUNT(*) FROM room          WHERE price_per_day <= 0;

-- V3: FK integrity check — orphan appointments
SELECT COUNT(*) AS orphan_appointments
FROM appointment a
LEFT JOIN patient p ON a.patient_id = p.patient_id
WHERE p.patient_id IS NULL;

-- V4: FK integrity check — orphan medical records
SELECT COUNT(*) AS orphan_records
FROM medical_record mr
LEFT JOIN patient p ON mr.patient_id = p.patient_id
WHERE p.patient_id IS NULL;

-- V5: CHECK constraint violations — billing paid > total
SELECT COUNT(*) AS billing_overpaid
FROM billing WHERE paid_amount > total_amount;

-- V6: Billing summary by payment status
SELECT payment_status,
       COUNT(*)                  AS bills,
       SUM(total_amount)         AS total_billed,
       SUM(paid_amount)          AS total_paid,
       SUM(total_amount - paid_amount) AS outstanding
FROM billing
GROUP BY payment_status;

-- V7: Patient admission count (top 10)
SELECT p.patient_id,
       CONCAT(p.first_name,' ',p.last_name) AS patient_name,
       COUNT(a.admission_id) AS total_admissions
FROM patient p
LEFT JOIN admission a ON p.patient_id = a.patient_id
GROUP BY p.patient_id, patient_name
ORDER BY total_admissions DESC
LIMIT 10;

-- V8: Prescriptions per medicine (top 10 most prescribed)
SELECT m.medicine_name, COUNT(pd.detail_id) AS times_prescribed
FROM medicine m
JOIN prescription_detail pd ON m.medicine_id = pd.medicine_id
GROUP BY m.medicine_id, m.medicine_name
ORDER BY times_prescribed DESC
LIMIT 10;

-- V9: Doctors with most appointments
SELECT CONCAT(d.first_name,' ',d.last_name) AS doctor_name,
       d.specialization, COUNT(a.appointment_id) AS appointments
FROM doctor d
LEFT JOIN appointment a ON d.doctor_id = a.doctor_id
GROUP BY d.doctor_id, doctor_name, d.specialization
ORDER BY appointments DESC
LIMIT 10;

-- V10: Lab test completion rate
SELECT status, COUNT(*) AS count,
       ROUND(COUNT(*)*100.0/(SELECT COUNT(*) FROM lab_test),2) AS pct
FROM lab_test
GROUP BY status;

-- V11: Revenue summary
SELECT
  SUM(total_amount)  AS gross_revenue,
  SUM(paid_amount)   AS collected,
  SUM(total_amount - paid_amount) AS outstanding,
  ROUND(SUM(paid_amount)/SUM(total_amount)*100,2) AS collection_rate_pct
FROM billing;

